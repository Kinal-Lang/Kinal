@dataclass(frozen=True)
class Entry:
    code: str
    severity: str
    prefix: str
    title: str
    detail: str


@dataclass(frozen=True)
class CategorySpec:
    prefix: str
    file_name: str
    title: str
    description: str


@dataclass(frozen=True)
class Example:
    summary: str
    bad: str
    good: str
    reason: str
    fix: str


