def build_example(entry: Entry) -> Example:
    match entry.prefix:
        case "ARG":
            return build_arg_example(entry)
        case "CTL":
            return build_ctl_example(entry)
        case "ENT":
            return build_ent_example(entry)
        case "GEN":
            return build_gen_example(entry)
        case "LNT":
            return build_lnt_example(entry)
        case "NAM":
            return build_nam_example(entry)
        case "RES":
            return build_res_example(entry)
        case "SAF":
            return build_saf_example(entry)
        case "SEM":
            return build_sem_example(entry)
        case "SYN":
            return build_syn_example(entry)
        case "TYP":
            return build_typ_example(entry)
        case _:
            return fallback_example(entry)


def build_arg_example(entry: Entry) -> Example:
    if entry.code == "E-ARG-00001":
        return Example(
            summary="调用点传入的参数个数和签名不一致。",
            bad="""
            Function int Add(int a, int b)
            {
                Return a + b;
            }

            int value = Add(1);
            """,
            good="""
            Function int Add(int a, int b)
            {
                Return a + b;
            }

            int value = Add(1, 2);
            """,
            reason="编译器在重载解析后找到了目标函数，但调用点提供的实参数量仍然不匹配。",
            fix="核对函数、方法或构造函数签名，补齐缺失参数、删除多余参数，或为遗漏参数提供默认值。",
        )
    if entry.code == "E-ARG-00002":
        return Example(
            summary="一旦开始使用命名参数，后续实参也必须继续使用命名形式。",
            bad="""
            Function string Format(string text, int indent = 0, bool uppercase = false)
            {
                Return text;
            }

            Format(text = "hello", true);
            """,
            good="""
            Function string Format(string text, int indent = 0, bool uppercase = false)
            {
                Return text;
            }

            Format(text = "hello", uppercase = true);
            """,
            reason="命名参数会改变参数匹配规则；如果后面再回到位置参数，编译器无法可靠判断每个值要绑定到哪个形参。",
            fix="要么全部使用位置参数，要么在第一个命名参数之后全部改为命名参数。",
        )
    if entry.code == "E-ARG-00003":
        return Example(
            summary="当前可调用目标不支持命名参数调用。",
            bad="""
            Function int Identity(int value)
            {
                Return value;
            }

            int result = Identity(value = 42);
            """,
            good="""
            Function int Identity(int value)
            {
                Return value;
            }

            int result = Identity(42);
            """,
            reason="并非所有调用目标都暴露了可按名称绑定的参数信息；某些内置调用、函数对象或特定调用路径只接受位置参数。",
            fix="改用位置参数；如果确实需要命名调用，改成支持命名参数的普通函数签名。",
        )
    if entry.code == "E-ARG-00004":
        return Example(
            summary="构造函数调用当前不接受命名参数。",
            bad="""
            Class Pair
            {
                Public Constructor(int left, int right)
                {
                }
            }

            Pair p = New Pair(left = 1, right = 2);
            """,
            good="""
            Class Pair
            {
                Public Constructor(int left, int right)
                {
                }
            }

            Pair p = New Pair(1, 2);
            """,
            reason="构造阶段的参数绑定规则与普通函数不同，当前前端没有把命名参数分发扩展到 `New` 调用路径。",
            fix="按构造函数形参顺序传入位置参数；如果需要更可读的构造方式，可以提供静态工厂函数。",
        )
    return Example(
        summary="同一个命名参数在一次调用中只能出现一次。",
        bad="""
        Function string Format(string text, int indent = 0)
        {
            Return text;
        }

        Format(text = "hello", text = "world");
        """,
        good="""
        Function string Format(string text, int indent = 0)
        {
            Return text;
        }

        Format(text = "hello", indent = 2);
        """,
        reason="同一个形参被重复赋值会让调用语义不明确，编译器无法判断最后应采用哪个值。",
        fix="确保每个命名形参最多出现一次；如果只是要覆盖默认值，只保留一个绑定。",
    )


