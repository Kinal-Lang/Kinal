CATEGORY_ORDER = ["ARG", "CTL", "ENT", "GEN", "LNT", "NAM", "RES", "SAF", "SEM", "SYN", "TYP"]


def clean(text: str) -> str:
    return textwrap.dedent(text).strip("\n")


def decode_c_string(value: str) -> str:
    return bytes(value, "utf-8").decode("unicode_escape")


def parse_entries() -> list[Entry]:
    text = REGISTRY_PATH.read_text(encoding="utf-8")
    entries: list[Entry] = []
    for match in ENTRY_RE.finditer(text):
        code = match.group("code")
        entries.append(
            Entry(
                code=code,
                severity="warning" if code.startswith("W-") else "error",
                prefix=code.split("-")[1],
                title=decode_c_string(match.group("title")),
                detail=decode_c_string(match.group("detail")),
            )
        )
    return entries


def ensure_output_dirs() -> None:
    DOCS_ROOT.mkdir(parents=True, exist_ok=True)


def format_code_block(code: str) -> list[str]:
    return ["```kinal", clean(code), "```"]


def render_entry(entry: Entry) -> list[str]:
    example = build_example(entry)
    severity_label = "警告" if entry.severity == "warning" else "错误"
    lines = [
        f"## {entry.code} — {entry.title}",
        "",
        f"- 级别：{severity_label}",
        f"- 默认详情：{entry.detail}",
        f"- 说明：{example.summary}",
        "",
        "错误示例：",
        "",
    ]
    lines.extend(format_code_block(example.bad))
    lines.extend(
        [
            "",
            "正确示例：",
            "",
        ]
    )
    lines.extend(format_code_block(example.good))
    lines.extend(
        [
            "",
            f"原因：{example.reason}",
            "",
            f"修复方式：{example.fix}",
            "",
        ]
    )
    return lines


def render_category_page(spec: CategorySpec, entries: list[Entry]) -> str:
    lines = [
        GENERATED_HEADER,
        f"# {spec.title}",
        "",
        spec.description,
        "",
        "本文中的示例都是最小复现片段，用来说明该错误码最常见的触发方式；少数更偏内部的诊断会使用最接近用户代码的表面写法来说明。",
        "",
        "---",
        "",
        "## 错误码目录",
        "",
        "| 错误码 | 标题 | 默认详情 |",
        "|------|------|----------|",
    ]
    for entry in entries:
        lines.append(f"| `{entry.code}` | {entry.title} | {entry.detail} |")
    lines.extend(["", "---", ""])
    for index, entry in enumerate(entries):
        if index:
            lines.extend(["---", ""])
        lines.extend(render_entry(entry))
    return "\n".join(lines).rstrip() + "\n"


