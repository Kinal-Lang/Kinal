def build_nam_example(entry: Entry) -> Example:
    if "already listed" in entry.detail:
        return Example(
            summary="同一个接口在继承列表中被重复写入。",
            bad="""
            Interface IValue
            {
                Function int Value();
            }

            Class Counter By IValue, IValue
            {
            }
            """,
            good="""
            Interface IValue
            {
                Function int Value();
            }

            Class Counter By IValue
            {
            }
            """,
            reason="重复列出同一接口不会增加能力，只会让继承关系变得冗余。",
            fix="在列表里每个接口只写一次。",
        )
    if "Variable already defined in this scope" in entry.detail:
        return Example(
            summary="同一作用域内重复声明了同名变量。",
            bad="""
            Static Function int Main()
            {
                int value = 1;
                int value = 2;
                Return value;
            }
            """,
            good="""
            Static Function int Main()
            {
                int left = 1;
                int right = 2;
                Return left + right;
            }
            """,
            reason="同名局部变量会遮蔽或冲突，让后续引用无法唯一绑定。",
            fix="重命名变量，或合并成一次声明。",
        )
    if "conflicts with" in entry.detail:
        return Example(
            summary="不同类型实体使用了同一个名字。",
            bad="""
            Class Value
            {
            }

            Enum Value
            {
                A, B
            }
            """,
            good="""
            Class ValueBox
            {
            }

            Enum ValueKind
            {
                A, B
            }
            """,
            reason="类型名共享同一个命名空间；类、接口、结构体和枚举之间不能同名共存。",
            fix="为冲突实体改名，保持每个公开类型名全局唯一。",
        )

    keyword_map = {
        "Duplicate Class": ("Class", "Demo"),
        "Duplicate Constructor": ("Constructor", "Demo"),
        "Duplicate Enum": ("Enum", "State"),
        "Duplicate Field": ("Field", "Count"),
        "Duplicate Function": ("Function", "Add"),
        "Duplicate Interface": ("Interface", "IDemo"),
        "Duplicate Method": ("Method", "Value"),
        "Duplicate Struct": ("Struct", "Pair"),
    }
    if entry.title == "Duplicate Enum" and "member" in entry.detail.lower():
        return Example(
            summary="枚举成员名重复。",
            bad="""
            Enum State
            {
                Ready,
                Ready
            }
            """,
            good="""
            Enum State
            {
                Ready,
                Done
            }
            """,
            reason="同一个枚举内的成员名必须唯一，否则点号访问无法区分。",
            fix="给重复成员改名。",
        )
    if entry.title in keyword_map:
        kind, name = keyword_map[entry.title]
        if kind == "Class":
            bad = f"Class {name}\n{{\n}}\n\nClass {name}\n{{\n}}"
            good = f"Class {name}\n{{\n}}\n\nClass {name}Extra\n{{\n}}"
        elif kind == "Constructor":
            bad = """
            Class Demo
            {
                Public Constructor(int value)
                {
                }

                Public Constructor(int value)
                {
                }
            }
            """
            good = """
            Class Demo
            {
                Public Constructor(int value)
                {
                }

                Public Constructor(string text)
                {
                }
            }
            """
        elif kind == "Enum":
            bad = """
            Enum State
            {
                Ready
            }

            Enum State
            {
                Done
            }
            """
            good = """
            Enum State
            {
                Ready
            }

            Enum Phase
            {
                Done
            }
            """
        elif kind == "Field":
            bad = """
            Class Counter
            {
                Public int Count;
                Public int Count;
            }
            """
            good = """
            Class Counter
            {
                Public int Count;
                Public int Total;
            }
            """
        elif kind == "Function":
            bad = """
            Function int Add(int a, int b)
            {
                Return a + b;
            }

            Function int Add(int a, int b)
            {
                Return a - b;
            }
            """
            good = """
            Function int Add(int a, int b)
            {
                Return a + b;
            }

            Function int Sub(int a, int b)
            {
                Return a - b;
            }
            """
        elif kind == "Interface":
            bad = """
            Interface IDemo
            {
                Function void Run();
            }

            Interface IDemo
            {
                Function void Stop();
            }
            """
            good = """
            Interface IRunner
            {
                Function void Run();
            }

            Interface IStopper
            {
                Function void Stop();
            }
            """
        elif kind == "Method":
            bad = """
            Class Counter
            {
                Public Function int Value()
                {
                    Return 1;
                }

                Public Function int Value()
                {
                    Return 2;
                }
            }
            """
            good = """
            Class Counter
            {
                Public Function int Value()
                {
                    Return 1;
                }

                Public Function int ValuePlusOne()
                {
                    Return 2;
                }
            }
            """
        else:
            bad = """
            Struct Pair
            {
                int Left;
            }

            Struct Pair
            {
                int Right;
            }
            """
            good = """
            Struct Pair
            {
                int Left;
            }

            Struct Size
            {
                int Right;
            }
            """

        return Example(
            summary="同一命名空间内出现了重复定义。",
            bad=bad,
            good=good,
            reason="同名实体会让后续引用解析到多个候选目标，编译器无法再保证绑定稳定。",
            fix="重命名重复实体，或者真正需要重载时改成参数列表不同的合法重载。",
        )

    return fallback_example(entry)


