def write_docs(entries: list[Entry]) -> None:
    ensure_output_dirs()
    overview_path = DOCS_ROOT / "index.md"
    overview_path.write_text(render_overview(entries), encoding="utf-8")

    for prefix in CATEGORY_ORDER:
        spec = CATEGORIES[prefix]
        page_entries = [entry for entry in entries if entry.prefix == prefix]
        page_path = DOCS_ROOT / spec.file_name
        page_path.write_text(render_category_page(spec, page_entries), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate zh-CN diagnostic code documentation from kn_diag_registry.c")
    parser.add_argument("--check", action="store_true", help="Only validate the registry and print counts")
    args = parser.parse_args()

    entries = parse_entries()
    if not entries:
        raise SystemExit(f"no diagnostic entries parsed from {REGISTRY_PATH}")

    unknown = sorted({entry.prefix for entry in entries if entry.prefix not in CATEGORIES})
    if unknown:
        raise SystemExit(f"unknown diagnostic prefixes: {', '.join(unknown)}")

    if args.check:
        print(f"parsed diagnostic codes: {len(entries)}")
        for prefix in CATEGORY_ORDER:
            count = sum(1 for entry in entries if entry.prefix == prefix)
            print(f"{prefix}: {count}")
        return 0

    write_docs(entries)
    print(f"generated zh-CN diagnostic docs: {len(entries)} codes -> {DOCS_ROOT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())